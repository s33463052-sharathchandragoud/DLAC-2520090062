"""
VisionPort Task 15: Estimate Traffic Waiting Time
Task Description: Estimate traffic waiting time based on vehicle queue and signal state.
Expected Output: Waiting-time report and real-time dashboard overlay.
"""

import cv2
import os
import sys

TASK_DIR = os.path.dirname(os.path.abspath(__file__))
OUTPUT_DIR = os.path.join(TASK_DIR, "outputs")
os.makedirs(OUTPUT_DIR, exist_ok=True)
PROJECT_ROOT = os.path.dirname(TASK_DIR)
SAMPLES_DIR = os.path.join(PROJECT_ROOT, "samples")
WEIGHTS_PATH = os.path.join(PROJECT_ROOT, "yolov8n.pt")
sys.path.append(PROJECT_ROOT)

from vehicle_detector import VisionPortDetector

print("=" * 60)
print("VisionPort Task 15: Traffic Waiting Time Estimation")
print("=" * 60)

detector = VisionPortDetector(WEIGHTS_PATH)
image_source = os.path.join(SAMPLES_DIR, "intersection.jpg")
if not os.path.exists(image_source):
    image_source = os.path.join(SAMPLES_DIR, "sample_traffic.jpg")

output_image = os.path.join(OUTPUT_DIR, "task15_waiting_time_output.jpg")
report_file = os.path.join(OUTPUT_DIR, "traffic_waiting_time_report.txt")

BASE_RED_DURATION_SEC = 25.0
DISPERSION_PER_VEHICLE_SEC = 2.4

frame = cv2.imread(image_source)
detections, _ = detector.detect_vehicles(frame)
queue_length = len(detections)

estimated_wait_time = BASE_RED_DURATION_SEC + (queue_length * DISPERSION_PER_VEHICLE_SEC)

if estimated_wait_time < 30:
    delay_category = "MINIMAL"
    delay_color = (0, 220, 0)
elif estimated_wait_time < 60:
    delay_category = "MODERATE"
    delay_color = (0, 200, 255)
else:
    delay_category = "SEVERE"
    delay_color = (0, 0, 255)

annotated = frame.copy()

for d in detections:
    x1, y1, x2, y2 = d["box"]
    cv2.rectangle(annotated, (x1, y1), (x2, y2), (255, 180, 0), 2)
    cv2.putText(annotated, f"{d['class_name']}", (x1, max(20, y1 - 8)),
                cv2.FONT_HERSHEY_SIMPLEX, 0.6, (255, 180, 0), 2)

cv2.rectangle(annotated, (20, 20), (520, 160), (20, 20, 20), -1)
cv2.rectangle(annotated, (20, 20), (520, 160), delay_color, 2)
cv2.putText(annotated, "VisionPort: Junction Waiting Time Analysis", (35, 50),
            cv2.FONT_HERSHEY_SIMPLEX, 0.65, (220, 220, 220), 1)
cv2.putText(annotated, f"Vehicles in Queue : {queue_length}", (35, 85),
            cv2.FONT_HERSHEY_SIMPLEX, 0.7, (255, 255, 255), 2)
cv2.putText(annotated, f"Estimated Wait    : {estimated_wait_time:.1f} seconds", (35, 115),
            cv2.FONT_HERSHEY_SIMPLEX, 0.7, delay_color, 2)
cv2.putText(annotated, f"Delay Severity    : {delay_category}", (35, 145),
            cv2.FONT_HERSHEY_SIMPLEX, 0.7, delay_color, 2)

cv2.imwrite(output_image, annotated)

report_content = f"""============================================================
VISIONPORT TRAFFIC MONITORING SYSTEM - WAITING TIME REPORT
============================================================
Analyzed Input        : {image_source}
Total Vehicles in Queue: {queue_length}
Base Red Phase        : {BASE_RED_DURATION_SEC:.1f} s
Dispersion Rate       : {DISPERSION_PER_VEHICLE_SEC:.1f} s/vehicle
------------------------------------------------------------
ESTIMATED WAITING TIME: {estimated_wait_time:.1f} seconds
DELAY SEVERITY        : {delay_category}
RECOMMENDED ACTION    : {"Normal signal cycle" if delay_category == "MINIMAL" else "Extend green split"}
------------------------------------------------------------
Generated by VisionPort Deep Learning Pipeline
"""

with open(report_file, "w", encoding="utf-8") as f:
    f.write(report_content)

print(report_content)
print(f"[OUTPUT] Report saved to: {report_file}")
print("[SUCCESS] Task 15 completed successfully!")
